"""Tests for the README check, the skill copy script, and the environment report."""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent.parent
README_TEXT = "# {title}\n\nThis directory exists only for a test fixture; the text names {title} so that each description differs from the others.\n"


def run(script: str, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(SCRIPTS / script), *args], capture_output=True, text=True, encoding="utf-8", timeout=120)


def write_readme(directory: Path, title: str) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "README.md").write_text(README_TEXT.format(title=title), encoding="utf-8")


class FixtureTestCase(unittest.TestCase):
    def setUp(self) -> None:
        self.root = Path(tempfile.mkdtemp(prefix="workspace test ä "))
        self.addCleanup(shutil.rmtree, self.root, ignore_errors=True)
        for rel in ("", ".agents", ".agents/skills", ".claude", ".claude/skills", "inbox", "inbox/imports"):
            write_readme(self.root / rel, rel or "root")


class ReadmeCheckTests(FixtureTestCase):
    def test_passes_and_ignores_intake_material(self) -> None:
        (self.root / "inbox" / "My draft folder").mkdir()
        result = run("check_readmes.py", str(self.root))
        self.assertEqual(result.returncode, 0, result.stdout)

    def test_reports_missing_short_and_identical_readmes(self) -> None:
        (self.root / "notes").mkdir()
        (self.root / "short").mkdir()
        (self.root / "short" / "README.md").write_text("# Short\n\nToo short.\n", encoding="utf-8")
        shutil.copy2(self.root / "inbox" / "README.md", self.root / ".agents" / "README.md")
        result = run("check_readmes.py", str(self.root))
        self.assertEqual(result.returncode, 1)
        self.assertIn("notes/", result.stdout)
        self.assertIn("short/README.md has 2 words", result.stdout)
        self.assertIn(".agents/README.md, inbox/README.md", result.stdout)


class SkillCopyTests(FixtureTestCase):
    def add_skill(self, name: str, description: str = "Does one test task.") -> Path:
        package = self.root / ".agents" / "skills" / name
        write_readme(package, name)
        (package / "SKILL.md").write_text(f"---\nname: {name}\ndescription: {description}\n---\n\n# Body\n", encoding="utf-8")
        return package

    def test_generates_checks_and_removes_copies(self) -> None:
        package = self.add_skill("demo-skill")
        self.assertEqual(run("sync_skills.py", "--check", str(self.root)).returncode, 1)
        self.assertEqual(run("sync_skills.py", str(self.root)).returncode, 0)
        copy = self.root / ".claude" / "skills" / "demo-skill"
        self.assertEqual((copy / "SKILL.md").read_bytes(), (package / "SKILL.md").read_bytes())
        self.assertIn("Generated by scripts/sync_skills.py", (copy / "README.md").read_text(encoding="utf-8"))
        self.assertEqual(run("sync_skills.py", "--check", str(self.root)).returncode, 0)
        self.assertEqual(run("check_readmes.py", str(self.root)).returncode, 0)

        (copy / "SKILL.md").write_text("hand edit", encoding="utf-8")
        self.assertIn("Out of date", run("sync_skills.py", "--check", str(self.root)).stdout)

        shutil.rmtree(package)
        self.assertEqual(run("sync_skills.py", str(self.root)).returncode, 0)
        self.assertFalse(copy.exists())

    def test_rejects_unquoted_colon_and_keeps_unmanaged_directories(self) -> None:
        self.add_skill("bad-skill", "Use when: this breaks YAML")
        handmade = self.root / ".claude" / "skills" / "handmade"
        handmade.mkdir(parents=True)
        result = run("sync_skills.py", str(self.root))
        self.assertEqual(result.returncode, 1)
        self.assertIn("must be quoted", result.stdout)
        self.assertIn("handmade was not generated", result.stdout)
        self.assertTrue(handmade.exists())


class EnvironmentReportTests(unittest.TestCase):
    def test_json_report_has_the_expected_sections(self) -> None:
        result = run("inspect_environment.py", "--json")
        self.assertEqual(result.returncode, 0, result.stderr)
        report = json.loads(result.stdout)
        self.assertEqual(set(report), {"os", "processor", "memory_bytes", "python", "pythons_on_path", "tools", "workspace"})
        self.assertIn(report["processor"]["python_bits"], (32, 64))

    @unittest.skipIf(sys.platform == "win32", "the stand-in executable is a POSIX shell script")
    def test_reports_a_tool_installed_in_the_workspace(self) -> None:
        root = Path(tempfile.mkdtemp(prefix="environment test ä "))
        self.addCleanup(shutil.rmtree, root, ignore_errors=True)
        (root / "scripts").mkdir()
        shutil.copy2(SCRIPTS / "inspect_environment.py", root / "scripts" / "inspect_environment.py")
        pandoc = root / ".tools" / "pandoc" / "9.9" / "bin" / "pandoc"
        pandoc.parent.mkdir(parents=True)
        pandoc.write_text("#!/bin/sh\necho 'pandoc 9.9'\n", encoding="utf-8")
        pandoc.chmod(0o755)
        result = subprocess.run([sys.executable, str(root / "scripts" / "inspect_environment.py"), "--json"], capture_output=True,
                                text=True, encoding="utf-8", timeout=120, env={"PATH": "/usr/bin:/bin"})
        self.assertEqual(result.returncode, 0, result.stderr)
        found = json.loads(result.stdout)["tools"]["pandoc"]
        self.assertEqual((found["location"], found["version"]), ("workspace .tools", "pandoc 9.9"))


if __name__ == "__main__":
    unittest.main()
