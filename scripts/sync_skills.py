#!/usr/bin/env python3
"""Generate and check the Claude Code copies of the canonical skill packages.

Each skill is written once in .agents/skills/<skill-id>/, where Codex finds it.
Claude Code reads project skills only from .claude/skills/, so this script copies
every canonical package there and writes a README that names the source
(AGENTS.md, "Skills"; docs/design-plan.md, Section 8).

Usage:
  python scripts/sync_skills.py [WORKSPACE_ROOT]          regenerate the copies
  python scripts/sync_skills.py --check [WORKSPACE_ROOT]  report differences only
Exit status: 0 when the copies match or were regenerated, 1 when problems remain.
Uses only the Python standard library.
"""

from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

CANONICAL = Path(".agents/skills")
COPIES = Path(".claude/skills")
GENERATED_MARK = "<!-- Generated by scripts/sync_skills.py; do not edit. -->"

# Codex requires name and description; Claude Code reads both. Other fields are
# not portable, so frontmatter stays a flat block of one-line fields.
SKILL_NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
MAX_NAME = 64
MAX_DESCRIPTION = 1024
UNSAFE_PLAIN_START = tuple("!&*[]{}|>%@`'\"#,")
JUNK = frozenset({"__pycache__", ".DS_Store", "Thumbs.db", "desktop.ini"})


def scalar(raw: str, key: str) -> str:
    """Decode a one-line YAML scalar; reject plain forms that YAML would misread."""
    if len(raw) >= 2 and raw[0] == raw[-1] == '"':
        return raw[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(raw) >= 2 and raw[0] == raw[-1] == "'":
        return raw[1:-1].replace("''", "'")
    if (
        raw.startswith(UNSAFE_PLAIN_START)
        or raw.startswith(("- ", "? ", ": "))
        or ": " in raw
        or " #" in raw
        or raw.endswith(":")
    ):
        raise ValueError(f"the {key} value must be quoted to be valid YAML")
    return raw


def frontmatter(skill_md: Path) -> dict[str, str]:
    """Return the one-line fields of the frontmatter block at the top of SKILL.md."""
    lines = skill_md.read_text(encoding="utf-8-sig").splitlines()
    if not lines or lines[0].rstrip() != "---":
        raise ValueError("does not start with a '---' frontmatter line")
    fields: dict[str, str] = {}
    for line in lines[1:]:
        if line.rstrip() == "---":
            return fields
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, value = line.partition(":")
        if not separator or line[:1].isspace():
            raise ValueError(f"has an unsupported frontmatter line {line!r}; keep each field on one line")
        fields[key.strip()] = scalar(value.strip(), key.strip())
    raise ValueError("has no closing '---' frontmatter line")


def package_problems(package: Path) -> list[str]:
    if len(package.name) > MAX_NAME or not SKILL_NAME.fullmatch(package.name):
        return ["the directory name must be lowercase words joined by hyphens, at most 64 characters"]
    problems = []
    if not (package / "README.md").is_file():
        problems.append("has no README.md")
    skill_md = package / "SKILL.md"
    if not skill_md.is_file():
        return problems + ["has no SKILL.md"]
    try:
        fields = frontmatter(skill_md)
    except (ValueError, UnicodeDecodeError) as error:
        return problems + [f"SKILL.md {error}"]
    if fields.get("name") != package.name:
        problems.append(f"SKILL.md name {fields.get('name')!r} must equal the directory name")
    description = fields.get("description", "")
    if not description:
        problems.append("SKILL.md has no description")
    elif len(description) > MAX_DESCRIPTION:
        problems.append(f"SKILL.md description has {len(description)} characters; the limit is {MAX_DESCRIPTION}")
    return problems


def files_in(directory: Path, include_readme: bool) -> dict[str, bytes]:
    """Return the files below directory, keyed by POSIX path, without OS and cache files."""
    files = {}
    for path in sorted(directory.rglob("*")):
        rel = path.relative_to(directory)
        if any(part in JUNK for part in rel.parts) or path.suffix == ".pyc" or not path.is_file():
            continue
        if include_readme or rel.as_posix() != "README.md":
            files[rel.as_posix()] = path.read_bytes()
    return files


def copy_readme(skill_id: str) -> bytes:
    text = (
        f"# {skill_id} (Claude Code copy)\n\n"
        "Generated copy of the canonical skill package in "
        f"[`.agents/skills/{skill_id}/`](../../../.agents/skills/{skill_id}/README.md), "
        "placed here because Claude Code reads project skills only from `.claude/skills/`. "
        "Do not edit files in this directory: change the canonical package, then run "
        "`python scripts/sync_skills.py`. Running `python scripts/sync_skills.py --check` "
        "reports any difference between the two copies.\n\n"
        f"{GENERATED_MARK}\n"
    )
    return text.encode("utf-8")


def same(rel: str, current: bytes | None, wanted: bytes) -> bool:
    if current is None:
        return False
    if rel == "README.md":
        # The generated README is compared as text, so a CRLF checkout still matches.
        return current.replace(b"\r\n", b"\n") == wanted
    return current == wanted


def compare(root: Path):
    """Return (problems, files to write, paths to remove, copy directories of valid packages)."""
    problems: list[str] = []
    writes: list[tuple[Path, bytes]] = []
    removals: list[Path] = []
    managed: list[Path] = []
    canonical_root, copies_root = root / CANONICAL, root / COPIES
    packages = sorted(p for p in canonical_root.iterdir() if p.is_dir() and p.name not in JUNK) if canonical_root.is_dir() else []
    for package in packages:
        found = package_problems(package)
        if found:
            problems.extend(f"{CANONICAL.as_posix()}/{package.name} {problem}" for problem in found)
            continue
        wanted = files_in(package, include_readme=False)
        wanted["README.md"] = copy_readme(package.name)
        copy = copies_root / package.name
        managed.append(copy)
        current = files_in(copy, include_readme=True) if copy.is_dir() else {}
        writes.extend((copy / rel, data) for rel, data in wanted.items() if not same(rel, current.get(rel), data))
        removals.extend(copy / rel for rel in sorted(current.keys() - wanted.keys()))
    if copies_root.is_dir():
        for copy in sorted(p for p in copies_root.iterdir() if p.is_dir() and p.name not in JUNK):
            if (canonical_root / copy.name).is_dir():
                continue
            readme = copy / "README.md"
            if readme.is_file() and GENERATED_MARK in readme.read_text(encoding="utf-8", errors="replace"):
                removals.append(copy)  # A generated copy whose canonical package was removed.
            else:
                problems.append(f"{COPIES.as_posix()}/{copy.name} was not generated from {CANONICAL.as_posix()}; move or remove it by hand")
    return problems, writes, removals, managed


def apply(writes: list[tuple[Path, bytes]], removals: list[Path], managed: list[Path]) -> None:
    for path, data in writes:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for path in removals:
        if path.is_dir():
            shutil.rmtree(path)
        else:
            path.unlink()
    # Remove directories left empty inside the generated copies only, deepest first.
    for copy in managed:
        for directory in sorted((p for p in copy.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True):
            if not any(directory.iterdir()):
                directory.rmdir()


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="backslashreplace")

    parser = argparse.ArgumentParser(description="Generate and check the Claude Code copies of the skill packages.")
    parser.add_argument("--check", action="store_true", help="report differences without writing")
    parser.add_argument(
        "root",
        nargs="?",
        type=Path,
        default=Path(__file__).resolve().parent.parent,
        help="workspace root (default: the parent of the scripts directory)",
    )
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if not (root / CANONICAL).is_dir():
        parser.error(f"no {CANONICAL.as_posix()} directory in {root}")

    problems, writes, removals, managed = compare(root)
    if args.check:
        for path, _ in writes:
            print(f"Out of date: {path.relative_to(root).as_posix()}")
        for path in removals:
            print(f"Not in the canonical package: {path.relative_to(root).as_posix()}")
    else:
        apply(writes, removals, managed)
        if writes or removals:
            print(f"Updated {len(writes)} file(s) and removed {len(removals)} path(s) in {COPIES.as_posix()}.")
    for problem in problems:
        print(f"Problem: {problem}")

    if problems or (args.check and (writes or removals)):
        print("Skill copy check failed." if args.check else "Skill copies were updated, but problems remain.")
        return 1
    print(f"Skill copies match: {len(managed)} package(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
